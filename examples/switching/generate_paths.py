"""Redraw conditional paths and integrate the trained model from Gaussian quantiles."""

import argparse
import hashlib
from pathlib import Path
from statistics import NormalDist

import numpy as np
import torch

from model import MarginalModel, integrate
from process import paths


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--checkpoint", type=Path, default=Path("reference/model.pt"))
    parser.add_argument(
        "--reference",
        type=Path,
        default=Path("reference/switching-01.npz"),
        help="Evaluation histogram and plotting grid to retain",
    )
    parser.add_argument("--output", type=Path, default=Path("artifacts/paths"))
    parser.add_argument("--count", type=int, default=6)
    parser.add_argument("--seed", type=int, default=831261016)
    args = parser.parse_args()
    if args.count < 1:
        parser.error("--count must be positive")
    torch.set_num_threads(2)
    checkpoint_sha256 = hashlib.sha256(args.checkpoint.read_bytes()).hexdigest()
    model = MarginalModel().eval()
    model.load_state_dict(
        torch.load(args.checkpoint, map_location="cpu", weights_only=True)["ema"]
    )
    with np.load(args.reference, allow_pickle=False) as saved:
        if str(saved["checkpoint_sha256"]) != checkpoint_sha256:
            raise ValueError(
                "The histogram was generated by different weights. Run assess.py "
                "with this checkpoint and pass its figure-data.npz as --reference."
            )
        common = {
            k: saved[k].copy()
            for k in (
                "time",
                "endpoint_samples",
                "target",
                "density_x",
                "density_y",
                "checkpoint_sha256",
            )
        }
    q = np.arange(2, 100, 2, dtype=np.float64) / 100
    source = np.array([NormalDist().inv_cdf(x) for x in q], dtype=np.float32)
    common["generated"] = integrate(model, torch.from_numpy(source), common["time"])
    common["source_quantiles"] = q
    args.output.mkdir(parents=True, exist_ok=True)
    for i in range(args.count):
        seed = args.seed + i
        conditional, signs, endpoints, vertices = paths(
            common["time"], 250, np.random.default_rng(seed)
        )
        np.savez_compressed(
            args.output / f"switching-{i+1:02d}.npz",
            **common,
            conditional=conditional,
            regimes=signs,
            conditional_endpoints=endpoints,
            conditional_vertices=np.concatenate(vertices),
            conditional_offsets=np.r_[0, np.cumsum([len(v) for v in vertices])],
            conditional_seed=np.array(seed),
        )


if __name__ == "__main__":
    main()
